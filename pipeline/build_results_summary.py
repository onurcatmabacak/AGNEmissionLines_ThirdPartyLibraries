#!/usr/bin/env python3
"""Write docs/RESULTS.md: every committed product's headline numbers.

The repository no longer ships its science data or its output trees (they are
gigabytes of third-party observations that every user would otherwise clone).
What it keeps is this table, generated from the ``run.json`` of every product, so
the results remain visible without the data.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "RESULTS.md"

# scalars worth surfacing, in priority order
KEYS = (
    "status", "chi2nu", "cstat_dof", "snr", "snr_integrated", "snr_rms",
    "velocity_kms", "fwhm_kms", "tau", "tau_peak", "amplitude", "tex_K",
    "centroid_kms", "E_cut_keV", "phoindex", "alpha_ox", "alpha_ox_err",
    "n_components", "n_spaxels_detected", "posterior_samples", "steps",
    "acceptance_fraction", "delta_cstat_cutoff", "fe_kalpha_delta_cstat",
    "delta_lnZ", "ln_evidence", "rms", "redshift", "kind",
)


def walk(obj, prefix=""):
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from walk(v, f"{prefix}{k}." if prefix else f"{k}.")
    elif isinstance(obj, list):
        # parameters live inside `components[0]`, `lines[0]`, ... : take the first
        # element so velocity_kms/fwhm_kms/snr are surfaced for the primary line
        for v in obj[:1]:
            yield from walk(v, prefix)
    else:
        yield prefix.rstrip("."), obj


def main() -> int:
    rows = []
    for run_json in sorted(ROOT.glob("outputs/**/run.json")):
        try:
            data = json.loads(run_json.read_text())
        except Exception:
            continue
        if not isinstance(data, dict):
            continue
        flat = dict(walk(data))
        picked = {}
        for key in KEYS:
            for k, v in flat.items():
                if k == key or k.endswith("." + key):
                    if isinstance(v, (int, float, str, bool)):
                        picked[key] = v
                        break
        rel = run_json.relative_to(ROOT / "outputs").parts
        tool = rel[0]
        source = rel[1] if len(rel) > 2 else rel[0]
        rows.append((source, tool, rel, picked))

    rows.sort()
    lines = ["# Results", "",
             "Every number below was produced from real observations by the tool named in",
             "the second column, and was committed with its own `run.json`, artefacts and",
             "caveat.  **The data and the output trees are no longer shipped** - cloning the",
             "repository used to mean downloading several gigabytes of third-party",
             "observations - so this table is the durable record.  `docs/CAVEAT_MATRIX.md`",
             "states what each tool may and may not claim.", "",
             "| source | tool | product | key numbers |", "|---|---|---|---|"]
    for source, tool, rel, picked in rows:
        bits = ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}"
                         for k, v in picked.items() if k != "status")
        status = picked.get("status", "")
        cell = (f"{status}; {bits}" if status else bits) or "-"
        variant = "/".join(rel[2:-1]) or "-"
        lines.append(f"| `{source}` | `{tool}` | `{variant}` | {cell} |")
    lines += ["", f"_Generated by `pipeline/build_results_summary.py` from {len(rows)} "
                  "committed products._", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} products)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
